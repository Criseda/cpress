// The archive decodes to its input, and the input compresses to exactly the
// archive.
void check_golden_archive(std::uint8_t codec_id, std::span<const std::uint8_t> input_bytes,
                          std::span<const std::uint8_t> archive_bytes) {
    const cpress::Bytes input(input_bytes.begin(), input_bytes.end());
    const cpress::Bytes archive(archive_bytes.begin(), archive_bytes.end());

    CHECK(cpress::read_header(archive).codec_id == codec_id);
    cpress::Bytes decoded;
    CHECK(!throws_error([&] { decoded = cpress::decompress(archive); }));
    CHECK(decoded == input);

    const cpress::Codec* codec = cpress::find_codec(codec_id);
    CHECK(codec != nullptr);
    if (codec == nullptr) return;
    CHECK(cpress::compress(input, *codec) == archive);
}

// The bytes of a text input, as the codec sees them.
cpress::Bytes bytes_of(std::string_view text) {
    return {text.begin(), text.end()};
}

