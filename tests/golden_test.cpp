void run_golden_tests() {
    check_golden_archive(kOrder0Id, bytes_of(kOrder0Text), kOrder0Archive);
    check_golden_archive(kMix6Id, bytes_of(kMix6Text), kMix6Archive);
    check_golden_archive(kMix9Id, bytes_of(kMix9Text), kMix9Archive);
    check_golden_archive(kItchId, kItchInput, kItchArchive);
    check_golden_archive(kWordsId, bytes_of(kWordsText), kWordsArchive);
}

